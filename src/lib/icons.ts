/** 品牌色相对亮度过低，在深色画布上需改用前景色。 */
export function isDarkBrand(icon: SimpleIcon): boolean {
  const [r, g, b] = [0, 2, 4].map((offset) => {
    const channel = Number.parseInt(icon.hex.slice(offset, offset + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.12;
}
